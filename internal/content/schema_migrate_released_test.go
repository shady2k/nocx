package content

// THE ACCEPTANCE SUITE FOR THE MIGRATION LADDER (nocx-lmb6v.2).
//
// Written from the acceptance criteria by somebody who did not write
// schema_migrate.go, which is the whole reason it is a separate bead
// (AGENTS.md rule 4). A migration that silently drops rows is the costliest
// defect this repo can ship once content.db stops being disposable, because it
// destroys the only copy of work a person cannot reproduce, and a test written
// by the implementation's author can only confirm that the code does what it
// was written to do.
//
// THE FIXTURES ARE REAL RELEASED SCHEMAS, and that is the criterion this file
// exists to satisfy. Both are the `schemaV1` constant lifted verbatim out of
// the tree at the commit where `const schemaVersion` held that number:
//
//	testdata/schema_v14.sql  ← a2fa7e3e, the last mainline commit at 14
//	testdata/schema_v13.sql  ← 1ccad4de, the last commit at 13
//
// Neither was generated by the current code. A fixture synthesised from the
// CURRENT schema would test the migration against the migration's own idea of
// the past, which is exactly the belief that is wrong on the day the migration
// is wrong: the past would agree with the present by construction, and the
// only thing the test could then discover is a typo. The two files carry their
// provenance in their own headers and are frozen.
//
// The two versions were chosen because they are the two sides of one boundary.
// 14 is the ladder's first rung, so it is the OLDEST database this build can
// carry forward; 13 is one below it, so it is the NEWEST database this build
// must refuse. A suite that tested either alone would not be testing a
// boundary at all.

