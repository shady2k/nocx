func TestAStampedSchema14DatabaseWithAnotherShapeIsRefusedBeforeMigration(t *testing.T) {
	path := filepath.Join(t.TempDir(), "content.db")
	aReleasedSchema14Database(t, path)
	rawExec(t, path,
		`DROP TABLE entries`,
		`PRAGMA user_version=14`,
	)

	_, err := Open(context.Background(), Config{
		Path: path, Key: schemaTestKey(), Budget: testBudgetInternal(), Logger: log.NewSlogAdapter(nil),
	})
	if err == nil {
		t.Fatal("Open accepted a database stamped schema 14 whose tables have a different shape")
	}
	if !strings.Contains(err.Error(), "missing") || !strings.Contains(err.Error(), `table "entries"`) {
		t.Fatalf("shape refusal reads %q; it must name the missing entries table", err)
	}
	if got := rawUserVersion(t, path); got != 14 {
		t.Fatalf("user_version = %d after shape refusal, want 14 — the ladder migrated a file before checking what its stamp described", got)
	}
	if scopeErr := rawTry(t, path, aContentScope); scopeErr == nil {
		t.Fatal("the malformed schema 14 file was migrated before its shape was refused")
	}
}

// assertTheRowsOfSchema14 is "its rows are present AND CORRECT afterwards",
// spelled out. Every assertion is a whole tuple read back from the raw file,
// because the failure this suite exists to catch is not an empty table — an
// empty table is loud — but a table with the right shape and the wrong
// contents.
func assertTheRowsOfSchema14(t *testing.T, path string) {
	t.Helper()
	for _, want := range []struct {
		what  string
		query string
		rows  []string
	}{
		{
			"the table the edge rebuilds, as whole tuples",
			`SELECT grant_id || '|' || resource_kind || '|' || resource_id
				FROM grant_scopes ORDER BY resource_kind`,
			[]string{"1|path|/srv/fourteen/path", "1|session|session-fourteen"},
		},
		{
			"the workspace, every column of it",
			`SELECT id || '|' || name || '|' || colour || '|' || position || '|' || created_at || '|' || payload || '|' || digest
				FROM workspaces WHERE id = 'ws-fourteen'`,
			[]string{"ws-fourteen|the workspace from before the upgrade|#123456|7|1400|{\"kept\":true}|digest-fourteen"},
		},
		{
			"the tab the user named, still attached to its workspace",
			`SELECT id || '|' || workspace_id || '|' || name FROM tabs`,
			[]string{"tab-fourteen|ws-fourteen|the tab the user named"},
		},
		{
			"the pane and its working directory",
			`SELECT id || '|' || tab_id || '|' || cwd || '|' || kind FROM panes`,
			[]string{"pane-fourteen|tab-fourteen|/srv/fourteen|local"},
		},
		{
			"the recorded command",
			`SELECT id || '|' || intent || '|' || kind || '|' || source || '|' || phase || '|' || status
				FROM entries WHERE id = 'entry-fourteen'`,
			[]string{"entry-fourteen|echo the command that must survive|shell|user|closed|success"},
		},
		{
			"the grant the scopes hang off",
			`SELECT id || '|' || execution_id || '|' || policy FROM authority_grants`,
			[]string{"1|1|{\"kept\":\"yes\"}"},
		},
		{
			// A counter that is not carried forward re-issues sequence
			// numbers that are already on rows, which is a corruption no row
			// count can see.
			"the ledger's own counter",
			`SELECT next FROM ledger_sequence WHERE id = 1`,
			[]string{"1"},
		},
	} {
		got := rawStrings(t, path, want.query)
		if len(got) != len(want.rows) {
			t.Fatalf("%s: read %d rows %q, want %d %q", want.what, len(got), got, len(want.rows), want.rows)
		}
		for i := range got {
			if got[i] != want.rows[i] {
				t.Fatalf("%s: row %d is %q, want %q — the rows came through the version change altered", want.what, i, got[i], want.rows[i])
			}
		}
	}
}

// rawStrings reads a one-column query off the encrypted file without going
// through Open, so the rows can be asked of a database the store REFUSED as
// well as one it accepted.
func rawStrings(t *testing.T, path, query string) []string {
	t.Helper()
	conn, done := rawConn(t, path)
	defer done()
	rows, err := conn.QueryContext(context.Background(), query)
	if err != nil {
		t.Fatalf("query %q: %v", query, err)
	}
	defer func() { _ = rows.Close() }()
	var out []string
	for rows.Next() {
		var s string
		if err := rows.Scan(&s); err != nil {
			t.Fatalf("scan %q: %v", query, err)
		}
		out = append(out, s)
	}
	if err := rows.Err(); err != nil {
		t.Fatalf("query %q: %v", query, err)
	}
	return out
}

// rawTryWithForeignKeys is rawTry with enforcement ON, which is how a
// CONSTRAINT that survived a table rebuild is asserted. The rebuild drops the
// old grant_scopes and renames a new one over it; a new table that forgot the
// reference to authority_grants would keep every row, pass every count, and
// silently stop enforcing the thing the column exists for.
func rawTryWithForeignKeys(t *testing.T, path, statement string) error {
	t.Helper()
	keyHex := hex.EncodeToString(schemaTestKey())
	db, err := driver.Open("file:"+path+"?vfs=adiantum", func(c *sqlite3.Conn) error {
		return c.Exec("PRAGMA hexkey='" + keyHex + "'")
	})
	if err != nil {
		t.Fatalf("raw open: %v", err)
	}
	defer func() { _ = db.Close() }()
	if _, pragmaErr := db.ExecContext(context.Background(), "PRAGMA foreign_keys=ON"); pragmaErr != nil {
		t.Fatalf("enable foreign keys: %v", pragmaErr)
	}
	_, err = db.ExecContext(context.Background(), statement)
	return err
}

// ── the happy path, on a real released database ───────────────────────────

// A DATABASE WRITTEN BY THE LAST RELEASED SCHEMA OPENS, AND ITS ROWS ARE STILL
// THERE AND STILL SAY WHAT THEY SAID.
//
// This is the criterion's headline and the paired positive that every refusal
// in this file is measured against: on an ordinary database, the thing
// succeeds. AGENTS.md records an epic whose every failure path was tested and
// where nothing asserted the feature was obtainable on a normal machine, where
// it never was — so the positive is not a courtesy, it is the assertion that
// makes the negatives mean anything.
func TestAReleasedSchema14DatabaseMigratesForwardWithItsRowsUnaltered(t *testing.T) {
	path := filepath.Join(t.TempDir(), "content.db")
	aReleasedSchema14Database(t, path)

	db, err := Open(context.Background(), Config{
		Path: path, Key: schemaTestKey(), Budget: testBudgetInternal(), Logger: log.NewSlogAdapter(nil),
	})
	if err != nil {
		t.Fatalf("Open over a released schema 14 database: %v — the last shipped shape must migrate, not refuse", err)
	}
	t.Cleanup(func() { _ = db.Close() })

	if got := rawUserVersion(t, path); got != schemaVersion {
		t.Fatalf("user_version = %d, want %d", got, schemaVersion)
	}
	assertTheRowsOfSchema14(t, path)

	// The edge did what it was for: the widened CHECK admits the kinds 15
	// added, and still refuses one no version ever defined. A rebuild that
	// dropped the constraint altogether would pass the first half alone.
	if scopeErr := rawTry(t, path, aContentScope); scopeErr != nil {
		t.Fatalf("a 'content' scope is refused after the migration: %v — the edge did not widen the CHECK", scopeErr)
	}
	if kindErr := rawTry(t, path,
		`INSERT INTO grant_scopes (grant_id, resource_kind, resource_id) VALUES (1, 'not-a-kind', 'x')`); kindErr == nil {
		t.Fatal("the rebuilt grant_scopes accepted a resource kind no schema ever defined — the widening dropped the CHECK instead of widening it")
	}

	// And the constraints that are not the point of the edge survived it too.
	if fkErr := rawTryWithForeignKeys(t, path,
		`INSERT INTO grant_scopes (grant_id, resource_kind, resource_id) VALUES (99, 'session', 'orphan')`); fkErr == nil {
		t.Fatal("the rebuilt grant_scopes accepted a scope pointing at a grant that does not exist — the table rebuild lost its foreign key")
	}
	if dupErr := rawTry(t, path,
		`INSERT INTO grant_scopes (grant_id, resource_kind, resource_id) VALUES (1, 'session', 'session-fourteen')`); dupErr == nil {
		t.Fatal("the rebuilt grant_scopes accepted a duplicate of a row it already holds — the table rebuild lost its primary key")
	}

	// AND THE STORE WORKS ON THE MIGRATED FILE. A database that opens and
	// then fails every write is the shape a stamp alone cannot rule out.
	if _, recordErr := db.Ledger().RecordCompleted(context.Background(), aRecordedCommand("echo after the upgrade")); recordErr != nil {
		t.Fatalf("RecordCompleted on the migrated database: %v", recordErr)
	}
	page, err := db.Ledger().QueryEntries(context.Background(), LedgerQuery{Scope: ScopeEverywhere, Limit: 50})
	if err != nil {
		t.Fatalf("QueryEntries after the migration: %v", err)
	}
	var intents []string
	for _, e := range page.Entries {
		intents = append(intents, e.Intent)
	}
	if !slicesContain(intents, "echo the command that must survive") {
		t.Fatalf("the command recorded under schema 14 is not readable through the store: %q", intents)
	}
	if !slicesContain(intents, "echo after the upgrade") {
		t.Fatalf("the command recorded after the migration is not readable: %q", intents)
	}
}

func slicesContain(hay []string, needle string) bool {
	for _, s := range hay {
		if s == needle {
			return true
		}
	}
	return false
}

// ── the floor, and that it is derived rather than written down ────────────

// THE NEWEST DATABASE THIS BUILD MUST REFUSE is one below the ladder's first
// rung, and it is refused with every row left where it was.
//
// The version is not spelled 13 in the assertions: it is computed from
// schemaLadder, so the day somebody retires the 14→15 rung this test starts
// asking about the new floor instead of going quietly green on an old one.
func TestAReleasedDatabaseOneBelowTheFirstRungIsRefusedWithEveryRowIntact(t *testing.T) {
	// The day the first rung moves, this asks for the released shape below the
	// NEW floor and goes red naming the file it needs, rather than skipping. A
	// boundary test that disables itself when the boundary moves is the one
	// failure mode it cannot afford: it would stay green for exactly as long as
	// the thing it guards was unguarded.
	floor := schemaLadder[0].from
	path := filepath.Join(t.TempDir(), "content.db")
	rawExec(t, path,
		releasedSchema(t, floor-1),
		`INSERT INTO workspaces (id, name, created_at) VALUES ('ws-thirteen', 'the workspace nobody may destroy', 1300)`,
		`INSERT INTO tabs (id, workspace_id, name) VALUES ('tab-thirteen', 'ws-thirteen', 'a tab from schema 13')`,
		`PRAGMA user_version=13`,
	)

	_, err := Open(context.Background(), Config{
		Path: path, Key: schemaTestKey(), Budget: testBudgetInternal(), Logger: log.NewSlogAdapter(nil),
	})
	if err == nil {
		t.Fatalf("Open accepted a schema %d database, which is below the ladder's first rung (%d)", floor-1, floor)
	}
	// The refusal is what a person reads in Settings, so it has to name the
	// numbers rather than merely report a mismatch.
	for _, want := range []string{
		fmt.Sprintf("%d", floor-1),
		fmt.Sprintf("%d", schemaVersion),
		fmt.Sprintf("%d", floor),
		"no rows were discarded",
	} {
		if !strings.Contains(err.Error(), want) {
			t.Fatalf("the refusal reads %q; it must contain %q", err.Error(), want)
		}
	}

	// NEVER REBUILT. This is the case the old code dropped every table for,
	// and the table NAMES here are entirely familiar to this build — which is
	// why the unknown-table gate that used to stand in front of the rebuild
	// could not have saved this file.
	if got := rawUserVersion(t, path); got != floor-1 {
		t.Fatalf("user_version = %d after the refusal, want %d — a refusal that restamps invites the next open to migrate a shape it never checked", got, floor-1)
	}
	if n := rawCount(t, path, `SELECT count(*) FROM workspaces`); n != 1 {
		t.Fatalf("workspaces holds %d rows after the refusal, want 1 — the refusal destroyed rows", n)
	}
	if rows := rawStrings(t, path, `SELECT name FROM tabs`); len(rows) != 1 || rows[0] != "a tab from schema 13" {
		t.Fatalf("tabs after the refusal = %q, want the row untouched", rows)
	}
	// Open cannot promise the bytes — it sets journal_mode before it reaches
	// the decision — so this asserts what it can: the file the store refused
	// still has every table schema 13 gave it, none added and none dropped.
	if n := rawCount(t, path,
		`SELECT count(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'`); n == 0 {
		t.Fatal("the refused database has no tables left at all")
	}
}

// THE FLOOR IS DERIVED FROM THE LADDER, NOT WRITTEN DOWN, and the only way to
// show that is to move the ladder and watch the floor move with it.
//
// The same file, the same function, two different ladders. Under the shipped
// chain it is below the first rung and is refused; under a chain with one more
// rung beneath it, it is simply an old database with a step, and the refusal
// does not happen. If the floor were a constant in the code, the second half
// would refuse too and this test would be the only thing that noticed.
func TestTheFloorMovesWithTheLadderRatherThanBeingAConstant(t *testing.T) {
	build := func(t *testing.T) string {
		t.Helper()
		path := filepath.Join(t.TempDir(), "content.db")
		rawExec(t, path,
			releasedSchema(t, 13),
			`INSERT INTO workspaces (id, name, created_at) VALUES ('ws-thirteen', 'kept', 1300)`,
			`PRAGMA user_version=13`,
		)
		return path
	}

	// Under the shipped ladder: refused, and the message names the ladder's
	// own first rung.
	shipped := build(t)
	conn, done := rawConn(t, shipped)
	shippedErr := migrateSchema(context.Background(), conn, schemaLadder, log.NewSlogAdapter(nil))
	done()
	if shippedErr == nil {
		t.Fatalf("migrateSchema accepted a schema 13 file under a ladder starting at %d", schemaLadder[0].from)
	}
	if !strings.Contains(shippedErr.Error(), fmt.Sprintf("starts at schema %d", schemaLadder[0].from)) {
		t.Fatalf("the refusal reads %q; it must name the ladder's first rung (%d) rather than a hard-coded floor",
			shippedErr.Error(), schemaLadder[0].from)
	}

	// Under a ladder with a rung beneath that one: not refused. The step is a
	// real ALTER — schema 13's `entries` has no `source` column, which is the
	// actual difference between the two released shapes — so this is a chain
	// that could genuinely exist, not a no-op that proves nothing.
	lowered := build(t)
	longer := append([]migrationStep{{
		from: 13, to: 14,
		apply: func(ctx context.Context, tx *sql.Tx) error {
			_, err := tx.ExecContext(ctx,
				`ALTER TABLE entries ADD COLUMN source TEXT NOT NULL DEFAULT 'user'`)
			return err
		},
	}}, schemaLadder...)
	conn, done = rawConn(t, lowered)
	loweredErr := migrateSchema(context.Background(), conn, longer, log.NewSlogAdapter(nil))
	done()
	if loweredErr != nil {
		t.Fatalf("migrateSchema refused a schema 13 file under a ladder that starts at 13: %v — the floor is a constant, not schemaLadder[0].from", loweredErr)
	}
	if got := rawUserVersion(t, lowered); got != schemaVersion {
		t.Fatalf("user_version = %d after walking the longer ladder, want %d", got, schemaVersion)
	}
	if n := rawCount(t, lowered, `SELECT count(*) FROM workspaces`); n != 1 {
		t.Fatalf("workspaces holds %d rows after walking two rungs, want 1", n)
	}
}

