// decl is the positional form of Declaration: the argument count is the
// completeness check at the declaration site, and Validate is the semantic
// check over the whole table.
func decl(id ID, kind Kind, owner Owner, phases []Phase, turn, max Deadline, silence, answer, recovery Bound, merge Merge, preempts []ID, waiting string, row Row, expired Expired) Declaration {
	return Declaration{
		ID: id, Kind: kind, Owner: owner, Phases: phases,
		Turn: turn, Max: max, Silence: silence, Answer: answer, Recovery: recovery,
		Merge: merge, Preempts: preempts, Waiting: waiting, Row: row, Expired: expired,
	}
}

func ph(name string, resources []Resource, deps []Domain) Phase {
	return Phase{Name: name, Resources: resources, Dependencies: deps}
}

func d(millis int64, basis Basis, note string) Deadline {
	return Deadline{Millis: millis, Basis: basis, Note: note}
}

func none() Bound { return Bound{Kind: BoundNone} }

func within(millis int64, basis Basis, note string) Bound {
	return Bound{Kind: BoundDeadline, Millis: millis, Basis: basis, Note: note}
}
