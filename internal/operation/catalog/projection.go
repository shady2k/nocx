package catalog

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// HandleName is the generated Go identifier for an operation's typed handle.
// It is exported because the generator writes it and the reference check reads
// it; both must spell it the same way.
func HandleName(id ID) string {
	var b strings.Builder
	b.WriteString("Op")
	upper := true
	for _, r := range string(id) {
		switch {
		case r >= 'a' && r <= 'z':
			if upper {
				b.WriteRune(r - 'a' + 'A')
			} else {
				b.WriteRune(r)
			}
			upper = false
		case r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}
	return b.String()
}

// HandleSource is the generated handles_gen.go body. The generator writes it
// and the staleness test compares it byte for byte.
func HandleSource() []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/operation/catalog/gen from the declaration table;
// DO NOT EDIT. A handle exists only for a declared operation, and the zero
// Method is refused by buildMethodSpecs.
//
// Regenerate: go run ./internal/operation/catalog/gen

package catalog

var (
`)
	decls := Declarations()
	width := 0
	for _, d := range decls {
		if n := len(HandleName(d.ID)); n > width {
			width = n
		}
	}
	for _, d := range decls {
		fmt.Fprintf(&b, "\t%-*s = methodHandle(%q)\n", width, HandleName(d.ID), d.ID)
	}
	b.WriteString(")\n")
	return b.Bytes()
}

type projectedDeclaration struct {
	Declaration
	Resources    []Resource `json:"resources"`
	Dependencies []Domain   `json:"dependencies"`
	Preempts     []ID       `json:"preempts"`
}

type manifestFile struct {
	Version    int                    `json:"version"`
	Operations []projectedDeclaration `json:"operations"`
}

// ManifestJSON is contracts/operations.json: every declaration with the
// derived resource and dependency unions, deterministic and sorted by id.
// One source, one projection; the generator writes these bytes and the test
// compares the committed file with them.
func ManifestJSON() ([]byte, error) {
	m := manifestFile{Version: 1}
	for _, d := range Declarations() {
		if d.Preempts == nil {
			d.Preempts = []ID{}
		}
		for i := range d.Phases {
			if d.Phases[i].Resources == nil {
				d.Phases[i].Resources = []Resource{}
			}
			if d.Phases[i].Dependencies == nil {
				d.Phases[i].Dependencies = []Domain{}
			}
		}
		resources := d.Resources()
		if resources == nil {
			resources = []Resource{}
		}
		deps := d.Dependencies()
		if deps == nil {
			deps = []Domain{}
		}
		m.Operations = append(m.Operations, projectedDeclaration{
			Declaration:  d,
			Resources:    resources,
			Dependencies: deps,
			Preempts:     d.Preempts,
		})
	}
	raw, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(raw, '\n'), nil
}
