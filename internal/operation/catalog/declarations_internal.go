// The internal half of the catalogue: work the backend starts by itself,
// rather than work a JSON-RPC call names. Each entry is an OPERATION, not the
// loop that runs it: ADR-8eej3e66 section 2 says a lifetime loop is registered
// separately with its owner and a bounded stop (see loops.go), and every
// iteration is an operation with the lifetime below.
//
// The list is enumerated from the backend's asynchronous entry points: the
// transfer paths, the poll loops, the recorder, the helper and ssh clients,
// the model paths, startup recovery and the background sweeps. `BeginInternal`
// is called at each entry point, and a static check refuses a declaration no
// production file references.

