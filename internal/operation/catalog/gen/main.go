// Command gen projects the declaration table into the two generated
// artifacts: the typed handles internal/transport registers with, and
// contracts/operations.json, which the schema validates and the renderer's
// deadline table is generated from.
//
// Run from the repository root: go run ./internal/operation/catalog/gen
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/shady2k/nocx/internal/operation/catalog"
)

func main() {
	root, err := repoRoot()
	if err != nil {
		fail(err)
	}
	if err := writeHandles(filepath.Join(root, "internal/operation/catalog/handles_gen.go")); err != nil {
		fail(err)
	}
	if err := writeManifest(filepath.Join(root, "contracts/operations.json")); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", dir)
		}
		dir = parent
	}
}

func handleName(id catalog.ID) string {
	var b strings.Builder
	b.WriteString("Op")
	upper := true
	for _, r := range string(id) {
		switch {
		case r >= 'a' && r <= 'z':
			if upper {
				b.WriteRune(r - 'a' + 'A')
			} else {
				b.WriteRune(r)
			}
			upper = false
		case r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}
	return b.String()
}

func writeHandles(path string) error {
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/operation/catalog/gen from the declaration table;
// DO NOT EDIT. A handle exists only for a declared operation, and the zero
// Method is refused by buildMethodSpecs.
//
// Regenerate: go run ./internal/operation/catalog/gen

package catalog

var (
`)
	for _, d := range catalog.Declarations() {
		fmt.Fprintf(&b, "\t%s = methodHandle(%q)\n", handleName(d.ID), d.ID)
	}
	b.WriteString(")\n")
	return os.WriteFile(path, b.Bytes(), 0o644)
}

type manifest struct {
	Version    int         `json:"version"`
	Operations []projected `json:"operations"`
}

type projected struct {
	catalog.Declaration
	Resources    []catalog.Resource `json:"resources"`
	Dependencies []catalog.Domain   `json:"dependencies"`
	Preempts     []catalog.ID       `json:"preempts"`
}

func writeManifest(path string) error {
	m := manifest{Version: 1}
	for _, d := range catalog.Declarations() {
		if d.Preempts == nil {
			d.Preempts = []catalog.ID{}
		}
		for i := range d.Phases {
			if d.Phases[i].Resources == nil {
				d.Phases[i].Resources = []catalog.Resource{}
			}
			if d.Phases[i].Dependencies == nil {
				d.Phases[i].Dependencies = []catalog.Domain{}
			}
		}
		resources := d.Resources()
		if resources == nil {
			resources = []catalog.Resource{}
		}
		deps := d.Dependencies()
		if deps == nil {
			deps = []catalog.Domain{}
		}
		m.Operations = append(m.Operations, projected{
			Declaration:  d,
			Resources:    resources,
			Dependencies: deps,
			Preempts:     d.Preempts,
		})
	}
	raw, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(raw, '\n'), 0o644)
}
