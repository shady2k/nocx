// ── the released fixtures ─────────────────────────────────────────────────

// releasedSchema reads one of the frozen scripts. It fails rather than skips
// when the file is missing: a suite that quietly stops testing the thing it is
// named after is worse than one that is red.
func releasedSchema(t *testing.T, version int) string {
	t.Helper()
	name := fmt.Sprintf("schema_v%d.sql", version)
	body, err := os.ReadFile(filepath.Join("testdata", name)) //nolint:gosec // a test-only path built from an int literal under this package's own testdata
	if err != nil {
		t.Fatalf("there is no released fixture for schema %d (%s): %v\n"+
			"Lift it verbatim out of the tree at the commit where `const schemaVersion` held %d, "+
			"and freeze it the way schema_v13.sql and schema_v14.sql are frozen. Do NOT generate it "+
			"from the current schema: a fixture the current code produced tests the migration "+
			"against the migration's own idea of the past.", version, name, err, version)
	}
	return string(body)
}

// aReleasedSchema14Database writes a database a shipped build of nocx would
// have written: the released DDL, rows in the tables the edge REBUILDS and in
// tables it never looks at, and the stamp.
//
// The values are deliberately distinctive rather than plausible. "Every row is
// still there" is a weaker claim than the one that matters — the edge rebuilds
// grant_scopes by copying it column by column into a new table, and a copy that
// pairs the right number of rows with the wrong values in them satisfies every
// count anybody could assert. So each string below is unique in the file, and
// assertTheRowsOfSchema14 reads them back as whole tuples.
// The creation-time pragmas precede the first table exactly as they do in
// Open. Omitting either would make this a schema-faithful but engine-different
// fixture: an upgraded file could then pass a parity test for the wrong reason.
func aReleasedSchema14Database(t *testing.T, path string) {
	t.Helper()
	rawExec(
		t, path,
		"PRAGMA auto_vacuum=INCREMENTAL",
		"PRAGMA journal_mode=WAL",
		releasedSchema(t, 14),
		// The released 14 startup sequence ran the api-run migration after
		// schemaV1, so this fixture carries those tables and their counter too.
		theTwoCounterEraAPIRunScript(t),
		`INSERT INTO api_run_schema (id, version) VALUES (1, 1)`,
		`INSERT INTO workspaces (id, name, colour, position, created_at, payload, digest)
			VALUES ('ws-fourteen', 'the workspace from before the upgrade', '#123456', 7, 1400, '{"kept":true}', 'digest-fourteen')`,
		`INSERT INTO tabs (id, workspace_id, name) VALUES ('tab-fourteen', 'ws-fourteen', 'the tab the user named')`,
		`INSERT INTO panes (id, tab_id, cwd, kind) VALUES ('pane-fourteen', 'tab-fourteen', '/srv/fourteen', 'local')`,
		`INSERT INTO environments (id, kind, first_seen) VALUES ('env-fourteen', 'local', 1400)`,
		`INSERT INTO environment_observations (id, environment_id, version, observed_at, criticality)
			VALUES (1, 'env-fourteen', 1, 1400, 'routine')`,
		`INSERT INTO entries
			(id, ingest_seq, client, digest, environment_id, pane_id, cwd, kind, source, intent, phase, status, submitted_at)
			VALUES ('entry-fourteen', 1, 'client-fourteen', 'digest-entry', 'env-fourteen', 'pane-fourteen',
			        '/srv/fourteen', 'shell', 'user', 'echo the command that must survive', 'closed', 'success', 1400)`,
		`INSERT INTO executions (id, entry_id, environment_obs_id) VALUES (1, 'entry-fourteen', 1)`,
		`INSERT INTO authority_grants (id, execution_id, version, issued_at, expires_at, policy)
			VALUES (1, 1, 1, 1400, 1460000, '{"kept":"yes"}')`,
		// The table the edge rebuilds. Two rows whose two text columns hold
		// values that are NOT interchangeable, so a copy that transposes them
		// is visible rather than merely suspected.
		`INSERT INTO grant_scopes (grant_id, resource_kind, resource_id) VALUES (1, 'session', 'session-fourteen')`,
		`INSERT INTO grant_scopes (grant_id, resource_kind, resource_id) VALUES (1, 'path', '/srv/fourteen/path')`,
		`INSERT INTO grant_effects (grant_id, effect) VALUES (1, 'observe')`,
		`UPDATE ledger_sequence SET next = 1 WHERE id = 1`,
		`PRAGMA user_version=14`,
	)
}

